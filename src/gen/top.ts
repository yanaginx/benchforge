import { HEADER } from './util.ts';
import type { Ctx } from './util.ts';

const clk = (ctx: Ctx) => ctx.model.dut?.clock?.name ?? 'clk';
const rst = (ctx: Ctx) => ctx.model.dut?.reset?.name ?? 'rst_n';
const rstLow = (ctx: Ctx) => (ctx.model.dut?.reset?.active ?? 'low') === 'low';
const w = (width?: number) => (width && width > 1 ? `[${width - 1}:0] ` : '');

export function interfaceSv(ctx: Ctx): string {
  const sig = (ctx.model.dut?.ports ?? []).filter(p => p.name !== clk(ctx) && p.name !== rst(ctx));
  return [
    HEADER('regenerated on every run.'),
    `interface ${ctx.project}_if (input logic ${clk(ctx)}, input logic ${rst(ctx)});`, '',
    ...(sig.length ? sig.map(p => `  logic ${w(p.width)}${p.name};`) : ['  // TODO: declare DUT signals (add dut.ports to the model)']),
    '', 'endinterface', '',
  ].join('\n');
}

export function topSv(ctx: Ctx): string {
  const dut = ctx.model.dut, period = dut?.clock?.period_ns ?? 10, c = clk(ctx), r = rst(ctx);
  const active = rstLow(ctx) ? '0' : '1', idle = rstLow(ctx) ? '1' : '0';
  const l = [
    HEADER('regenerated on every run.'), '`timescale 1ns/1ps', '',
    `module ${ctx.project}_tb_top;`, '  import uvm_pkg::*;', '  `include "uvm_macros.svh"', `  import ${ctx.project}_pkg::*;`, '',
    `  logic ${c} = 1'b0;`, `  logic ${r};`, `  always #(${period} / 2.0) ${c} = ~${c};`, '',
    '  initial begin', `    ${r} = 1'b${active};`, `    repeat (5) @(posedge ${c});`, `    ${r} = 1'b${idle};`, '  end', '',
    `  ${ctx.project}_if vif (.${c}(${c}), .${r}(${r}));`, '',
  ];
  if (dut) {
    const conns = [`.${c}(${c})`, `.${r}(${r})`, ...(dut.ports ?? []).filter(p => p.name !== c && p.name !== r).map(p => `.${p.name}(vif.${p.name})`)];
    l.push(`  ${dut.name} dut (${conns.join(', ')});`, '');
  } else l.push('  // TODO: instantiate the DUT and connect it to vif', '');
  l.push('  initial begin', `    uvm_config_db#(virtual ${ctx.project}_if)::set(null, "*", "vif", vif);`, '    run_test();', '  end', '', 'endmodule', '');
  return l.join('\n');
}

export function filelist(ctx: Ctx, pkgFile: string): string {
  const p = ctx.project;
  return [
    '# Generated by benchforge. Order matters: interface, package, top.',
    `# VCS:    vcs -sverilog -full64 -ntb_opts uvm-${ctx.uvm} -f filelist.f -o simv`,
    `# Questa: vlog -sv -f filelist.f +incdir+$UVM_HOME/src $UVM_HOME/src/uvm_pkg.sv  (or: vlog -L mtiUvm -sv -f filelist.f)`,
    '# Add your DUT sources above the tb files.',
    '+incdir+gen', '+incdir+user',
    `gen/${p}_if.sv`, `gen/${pkgFile}`, `gen/${p}_tb_top.sv`, '',
  ].join('\n');
}
